def _serialize_session(doc):
    if not doc:
        return None
    try:
        completed = json.loads(doc.completed_steps_json or "[]")
    except Exception:
        completed = []
    return {
        "name": doc.name,
        "status": doc.status,
        "target_environment": doc.target_environment,
        "current_step": cint(doc.current_step or 1),
        "completed_steps": completed,
        "started_by": doc.started_by,
        "started_at": str(doc.started_at) if doc.started_at else None,
        "completed_by": doc.completed_by,
        "completed_at": str(doc.completed_at) if doc.completed_at else None,
        "duration_seconds": cint(doc.duration_seconds),
        "reset_by": doc.reset_by,
        "reset_at": str(doc.reset_at) if doc.reset_at else None,
        "reset_reason": doc.reset_reason or "",
        "touched_mappings": doc.touched_mappings or "",
        "activity_log": [
            {
                "timestamp": str(l.timestamp) if l.timestamp else "",
                "user": l.user,
                "step_no": cint(l.step_no),
                "action": l.action,
                "result": l.result,
                "ref_doctype": l.ref_doctype,
                "ref_docname": l.ref_docname,
                "details": l.details,
            }
            for l in reversed(doc.activity_log or [])
        ],
    }


def _load_session(session_name):
    if not session_name or not frappe.db.exists("DRC Setup Session", session_name):
        raise ProblemError("session-missing", 404, _("Setup Session {0} not found.").format(session_name))
    return frappe.get_doc("DRC Setup Session", session_name)


@frappe.whitelist()
@api_endpoint
def get_state():
    """Return full wizard state: active/completed/recent sessions, live docs, and ERPNext preflight."""
    _ensure_admin()

    in_prog = frappe.get_all(
        "DRC Setup Session",
        filters={"status": "In Progress"},
        order_by="modified desc",
        limit=1,
        pluck="name",
    )
    active_session = frappe.get_doc("DRC Setup Session", in_prog[0]) if in_prog else None

