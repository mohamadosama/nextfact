@frappe.whitelist()
@api_endpoint
def save_step(session_name, step_no, data=None):
    """Persist step input directly into NextFact live DocTypes & advance wizard session."""
    _ensure_admin()
    s = _load_session(session_name)
    step_no = cint(step_no)
    payload = _parse_json_arg(data, {})

    st = frappe.get_single("DRC Fact Settings")
    action_label = f"Completed Step {step_no}"
    ref_dt = "DRC Fact Settings"
    ref_dn = "DRC Fact Settings"
    details = ""

    if step_no == 1:
        env = "production" if payload.get("target_environment") == "production" else "test"
        s.target_environment = env
        action_label = f"Mode & Pre-Flight confirmed ({env})"
        ref_dt = "DRC Setup Session"
        ref_dn = s.name
        details = f"Target environment set to {env}"

    elif step_no == 2:
        if payload.get("api_base_url"):
            st.api_base_url = payload["api_base_url"].strip().rstrip("/")
            st.save(ignore_permissions=True)
        action_label = "Saved Gateway URL & POS Mappings"
        details = f"API Base URL: {st.api_base_url}"

    elif step_no == 3:
        st.default_tax_group = (payload.get("default_tax_group") or "K").strip().upper()
        st.default_price_mode = payload.get("default_price_mode") or "ttc"
        st.default_item_type = payload.get("default_item_type") or "BIE"
        st.ui_wait_seconds = max(5, cint(payload.get("ui_wait_seconds") or st.ui_wait_seconds or 45))
        st.save(ignore_permissions=True)
        action_label = "Saved Tax Group & Fiscal Defaults"
        details = f"Tax Group={st.default_tax_group}, Price Mode={st.default_price_mode}, Item Type={st.default_item_type}"

    elif step_no == 4:
        pm_rows = payload.get("payment_map") or []
        st.set("payment_map", [])
        for row in pm_rows:
            if row.get("erpnext_mode_of_payment") and row.get("drc_payment_code"):
                st.append("payment_map", {
                    "erpnext_mode_of_payment": row["erpnext_mode_of_payment"],
                    "drc_payment_code": row["drc_payment_code"],
                })
        st.save(ignore_permissions=True)
        action_label = f"Saved Payment Method Mapping ({len(st.payment_map)} rows)"
        details = ", ".join(f"{r.erpnext_mode_of_payment}->{r.drc_payment_code}" for r in st.payment_map)

    elif step_no == 5:
        st.receipt_company_name = (payload.get("receipt_company_name") or "").strip()
        st.receipt_language = "fr" if payload.get("receipt_language") == "fr" else "en"
        st.tax_regime_label = (payload.get("tax_regime_label") or "Régime Normal").strip()
        st.sfe_isf = (payload.get("sfe_isf") or "MIN-LOG-01").strip()
        st.generated_by_text = (payload.get("generated_by_text") or "Generated by DRCFACT").strip()
        st.certification_text = (payload.get("certification_text") or "").strip()
        st.certified_software_text = (payload.get("certified_software_text") or "").strip()
        st.receipt_footer = (payload.get("receipt_footer") or "").strip()
        st.show_fx_on_receipt = cint(payload.get("show_fx_on_receipt", 1))
        st.delivery_note_show_prices = cint(payload.get("delivery_note_show_prices", 1))
        st.save(ignore_permissions=True)
        action_label = "Saved Thermal Receipt & Branding"
        details = f"Lang={st.receipt_language}, Regime={st.tax_regime_label}"

    elif step_no == 6:
        route_cfg = payload.get("new_route")
        if route_cfg and route_cfg.get("company") and route_cfg.get("target_mapping"):
            r = frappe.new_doc("DRC POS Route")
            r.priority = cint(route_cfg.get("priority") or 10)
            r.enabled = 1
            r.company = route_cfg["company"]
            r.target_mapping = route_cfg["target_mapping"]
            r.ask_cashier = cint(route_cfg.get("ask_cashier", 0))
            r.pos_profile = route_cfg.get("pos_profile") or None
            r.warehouse = route_cfg.get("warehouse") or None
            r.insert(ignore_permissions=True)
            ref_dt = "DRC POS Route"
            ref_dn = r.name
            action_label = "Created Conditional POS Route"
            details = f"{r.pos_profile or r.warehouse or 'All'} -> {r.target_mapping}"
        else:
            action_label = "Reviewed POS Routing & Roles"
            ref_dt = "DRC POS Route"
            ref_dn = ""
            details = "POS Profile direct mapping verified"

    try:
        completed = set(json.loads(s.completed_steps_json or "[]"))
    except Exception:
        completed = set()
    completed.add(step_no)
    s.completed_steps_json = json.dumps(sorted(completed))
    s.current_step = min(7, max(cint(s.current_step), step_no + 1))

    _append_log(s, step_no, action_label, "Success", ref_dt, ref_dn, details)
    s.save(ignore_permissions=True)
    frappe.db.commit()

    return {
        "session": _serialize_session(s),
        "settings": _serialize_settings(),
        "routes": _serialize_routes(),
    }


@frappe.whitelist()
@api_endpoint
def complete_session(session_name, enable_integration=1, disable_sandbox_mappings=0):
    """Finalize Setup Wizard, toggle DRC Fact Settings.enabled, and seal session duration."""
    _ensure_admin()
    s = _load_session(session_name)

    enable_flag = cint(enable_integration)
    st = frappe.get_single("DRC Fact Settings")
    st.enabled = enable_flag
    st.save(ignore_permissions=True)

    disabled_test = []
    if cint(disable_sandbox_mappings) and s.target_environment == "production":
        for m_name in frappe.get_all("DRC POS Mapping", filters={"environment": "test", "enabled": 1}, pluck="name"):
            frappe.db.set_value("DRC POS Mapping", m_name, "enabled", 0)
            disabled_test.append(m_name)

    now = now_datetime()
    s.status = "Completed"
    s.completed_by = frappe.session.user
    s.completed_at = now
    if s.started_at:
        s.duration_seconds = max(1, int(time_diff_in_seconds(now, s.started_at)))

    try:
        completed = set(json.loads(s.completed_steps_json or "[]"))
    except Exception:
        completed = set()
    completed.add(7)
    s.completed_steps_json = json.dumps(sorted(completed))
    s.current_step = 7

    _append_log(
        s,
        7,
        f"Setup Completed (Integration {'Enabled' if enable_flag else 'Saved Disabled'})",
        "Success",
        "DRC Fact Settings",
        "DRC Fact Settings",
        f"Disabled sandbox mappings: {', '.join(disabled_test)}" if disabled_test else "Ready for fiscalization",
    )
    s.save(ignore_permissions=True)
    frappe.db.commit()

    return {
        "session": _serialize_session(s),
        "settings": _serialize_settings(),
        "mappings": _serialize_mappings(),
    }


@frappe.whitelist()
@api_endpoint
def reset_session(session_name, reason="Admin requested wizard reset"):
    """Archive current wizard session cleanly so a fresh audit session can begin."""
    _ensure_admin()
    s = _load_session(session_name)
    s.status = "Reset / Archived"
    s.reset_by = frappe.session.user
    s.reset_at = now_datetime()
    s.reset_reason = (reason or "Admin requested wizard reset")[:300]
    _append_log(s, s.current_step, "Wizard Session Reset & Archived", "Warning", "DRC Setup Session", s.name, s.reset_reason)
    s.save(ignore_permissions=True)
    frappe.db.commit()

    return {"session": _serialize_session(s)}
