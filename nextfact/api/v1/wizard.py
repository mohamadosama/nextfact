ALLOWED_ROLES = ["NextFact Admin", "System Manager"]

DEFAULT_PAYMENT_SUGGESTIONS = {
    "cash": "ESPECES",
    "especes": "ESPECES",
    "wire transfer": "VIREMENT",
    "bank draft": "VIREMENT",
    "bank": "VIREMENT",
    "credit card": "CARTEBANCAIRE",
    "card": "CARTEBANCAIRE",
    "cheque": "CHEQUES",
    "check": "CHEQUES",
    "mobile money": "MOBILEMONEY",
    "mpesa": "MOBILEMONEY",
    "airtel": "MOBILEMONEY",
    "orange": "MOBILEMONEY",
}


def _ensure_admin():
    frappe.only_for(ALLOWED_ROLES)


def _parse_json_arg(val, default=None):
    if val is None or val == "":
        return default
    if isinstance(val, (dict, list)):
        return val
    return json.loads(val)


def _append_log(session, step_no, action, result="Success", ref_doctype=None, ref_docname=None, details=None):
    if not session:
        return
    session.append("activity_log", {
        "timestamp": now_datetime(),
        "user": frappe.session.user,
        "step_no": cint(step_no),
        "action": str(action or "")[:140],
        "result": result or "Success",
        "ref_doctype": ref_doctype or "",
        "ref_docname": ref_docname or "",
        "details": str(details or "")[:500],
    })


def _get_preflight():
    companies = frappe.get_all(
        "Company",
        fields=["name", "company_name", "default_currency", "default_expense_account", "tax_id"],
        order_by="name asc",
    )
    pos_profiles = frappe.get_all(
        "POS Profile",
        filters={"disabled": 0},
        fields=["name", "company", "warehouse", "currency", "cost_center", "selling_price_list"],
        order_by="name asc",
    )
    modes_of_payment = frappe.get_all(
        "Mode of Payment",
        filters={"enabled": 1},
        fields=["name", "type"],
        order_by="name asc",
    )
    for mop in modes_of_payment:
        key = (mop.name or "").strip().lower()
        suggested = DEFAULT_PAYMENT_SUGGESTIONS.get(key)
        if not suggested:
            if "mobile" in key or "money" in key:
                suggested = "MOBILEMONEY"
            elif "card" in key or "carte" in key:
                suggested = "CARTEBANCAIRE"
            elif (mop.type or "").lower() == "cash":
                suggested = "ESPECES"
            elif (mop.type or "").lower() == "bank":
                suggested = "VIREMENT"
            else:
                suggested = "AUTRE"
        mop["suggested_drc_code"] = suggested

    items_total = frappe.db.count("Item", {"disabled": 0})
    items_missing_expense = frappe.db.sql(
        """
        SELECT COUNT(DISTINCT i.name)
        FROM `tabItem` i
        LEFT JOIN `tabItem Default` id ON id.parent = i.name AND id.parenttype = 'Item'
        WHERE i.disabled = 0 AND i.is_stock_item = 1
          AND (id.expense_account IS NULL OR id.expense_account = '')
        """
    )[0][0]

    installed = frappe.get_installed_apps()
    fiscal_count = frappe.db.count("DRC Fiscal Invoice")
    normalized_count = frappe.db.count("DRC Fiscal Invoice", {"status": ["in", ["Normalized", "Normalized (Test)"]]})

    return {
        "companies": companies,
        "pos_profiles": pos_profiles,
        "modes_of_payment": modes_of_payment,
        "items_total": items_total,
        "items_missing_expense": cint(items_missing_expense),
        "pos_next_installed": "pos_next" in installed,
        "fiscal_invoices_total": fiscal_count,
        "fiscal_invoices_normalized": normalized_count,
    }


